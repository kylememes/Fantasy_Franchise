export function cardValues(
  position: string,
  values: Record<string, number>,
  kind: "ratings" | "statistics",
): [string, number][] {
  const keys =
    (kind === "ratings" ? positionAttributes[position] : stats[position]) || [];
  return keys
    .filter((k) => Number.isFinite(values[k]))
    .map((k) => [k, values[k]]);
}
